#!/usr/bin/env node
/**
 * Quality Gate — the anti-slop system every deliverable must pass through.
 *
 * QA Critic → Evidence Checker → Requirement Coverage
 *
 * This runs BEFORE any deliverable is submitted to ACP. It checks:
 * 1. Quality: Does the deliverable address every requirement in the job?
 * 2. Evidence: Are required files present and machine-verifiable?
 * 3. Slop: AI-generated boilerplate, fabricated claims, placeholder text
 *
 * A deliverable must score >= 85 to pass. Below that → regenerate or repair.
 */

const { BaseSkill } = require('../core/base_skill');
const path = require('path');
const fs = require('fs');

// Banned AI-slop phrases (English)
const BANNED_PHRASES = [
  /as an AI/i,
  /I cannot browse/i,
  /as an AI language model/i,
  /in today's digital age/i,
  /in today's (?:fast[-\s]?paced|ever[-\s]?evolving|dynamic landscape)/i,
  /it is important to note/i,
  /it's worth noting that/i,
  /please note that/i,
  /kindly note/i,
  /AI-generated/i,
  /generated by AI/i,
  /Lorem ipsum/i,
  /placeholder/i,
  /insert here/i,
  /example\.com/i,
  /TODO/i,
  /FIXME/i,
];

// Structural slop patterns
const STRUCTURAL_PATTERNS = [
  {
    name: 'Rule of Three',
    // Detect three consecutive list items or three consecutive short sentences
    test: (text) => {
      const lines = text.split('\n');
      let triple = 0;
      for (const line of lines) {
        if (/^[-*]\s/.test(line) && line.trim().length < 60) {
          triple++;
          if (triple >= 3) return true;
        } else {
          triple = 0;
        }
      }
      return false;
    }
  },
  {
    name: 'Uniform sentence length',
    test: (text) => {
      // Split into sentences, check for 3 consecutive sentences of similar length
      const sentences = text.split(/[.!?]+/).filter(s => s.trim().length > 5);
      if (sentences.length < 3) return false;
      let matches = 0;
      for (let i = 0; i < sentences.length - 2; i++) {
        const l1 = sentences[i].trim().length;
        const l2 = sentences[i+1].trim().length;
        const l3 = sentences[i+2].trim().length;
        if (Math.abs(l1-l2) <= 3 && Math.abs(l2-l3) <= 3) {
          matches++;
          if (matches >= 3) return true;
        }
      }
      return false;
    }
  },
  {
    name: 'AI listicle opener',
    test: (text) => /\b(In this|This (?:article|guide|post)|Today we'll|Let's explore)/i.test(text)
  },
];

class QualityGate {
  constructor() {
    this.passed = true;
    this.score = 100;
    this.issues = [];
    this.evidence = [];
  }

  /**
   * Check a deliverable against all quality criteria.
   * @param {object} job - The ACP job { description, name, requirements? }
   * @param {object} result - { deliverable, evidence, artifacts, skill_name }
   * @returns {object} { passed, score, issues, evidence }
   */
  check(job, result) {
    const dg = new Date();
    dg.toISOString();

    // --- Requirement coverage ---
    const requirements = this.extract_requirements(job, result);
    const coverage = this.check_requirement_coverage(job, result, requirements);

    // --- Slop detection ---
    const slopScore = this.check_slop(result.deliverable || '');

    // --- Evidence quality ---
    const evidenceScore = this.check_evidence(result.evidence || []);

    // --- Compute final score ---
    this.score = Math.round(
      coverage.score * 0.40 +
      slopScore * 0.35 +
      evidenceScore * 0.25
    );

    this.passed = this.score >= 85;

    if (!this.passed) {
      this.issues.push(`Overall quality score: ${this.score}/100 (threshold: 85)`);
    }

    return {
      passed: this.passed,
      score: this.score,
      issues: this.issues,
      evidence: this.evidence,
      requirements_found: requirements.length,
      requirement_coverage: coverage.score,
      slop_score: slopScore,
      evidence_score: evidenceScore,
    };
  }

  /** Extract explicit and implicit requirements from the job description */
  extract_requirements(job, result) {
    const reqs = [];

    // Explicit requirements from job description
    const desc = job.description || job.name || '';

    // Look for numbered requirements, "must include", "should", etc.
    const requirementPatterns = [
      /must\s+(?:include|have|provide|produce)/gi,
      /should\s+(?:include|have|provide|produce)/gi,
      /required.*:/gi,
      /\d+\.\s*\w+/g, // numbered list items
    ];

    for (const pattern of requirementPatterns) {
      let match;
      const regex = new RegExp(pattern.source, pattern.flags);
      while ((match = regex.exec(desc)) !== null) {
        if (match[0].trim().length > 5) {
          reqs.push(match[0].trim());
        }
      }
    }

    return reqs;
  }

  /** Check that all requirements are addressed in the deliverable */
  check_requirement_coverage(job, result, requirements) {
    if (requirements.length === 0) {
      return { score: 100, missing: [] };
    }

    const deliverable = (result.deliverable || '') + (result.evidence || []).join(' ');
    const missing = [];

    for (const req of requirements) {
      // Simple keyword-based check
      const keywords = req.toLowerCase().replace(/must|should|required|include/gi, '')
        .split(/\s+/).filter(w => w.length > 3);
      const found = keywords.some(kw => deliverable.toLowerCase().includes(kw));
      if (!found) {
        missing.push(req);
      }
    }

    const coverageScore = 100 - (missing.length / Math.max(requirements.length, 1)) * 100;
    this.issues.push(...missing.map(m => `Unmet requirement: ${m}`));

    return { score: Math.round(coverageScore), missing };
  }

  /** AI-slop detection — scan text for banned phrases and structural patterns */
  check_slop(text) {
    let score = 100;
    let slopCount = 0;

    // Phrase-level banned words (with deduplication)
    const seen = new Set();
    for (const phrase of BANNED_PHRASES) {
      const matches = text.match(new RegExp(phrase.source, phrase.flags));
      if (matches) {
        slopCount += matches.length;
        const label = phrase.source;
        if (!seen.has(label)) {
          this.issues.push(`Banned phrase "${label}" found ${matches.length} time(s)`);
          seen.add(label);
        }
      }
    }

    // Structural patterns
    for (const pattern of STRUCTURAL_PATTERNS) {
      if (pattern.test(text)) {
        slopCount++;
        this.issues.push(`Structural slop detected: ${pattern.name}`);
      }
    }

    // Penalty: 5 points per slop instance, floor at 0
    score = Math.max(0, 100 - slopCount * 5);
    this.evidence.push(`Slop scan: ${slopCount} violations found, score ${score}/100`);

    return score;
  }

  /** Evidence quality check */
  check_evidence(evidence) {
    if (!evidence || evidence.length === 0) {
      this.issues.push('No evidence artifacts provided');
      return 0;
    }

    let score = 100;
    let issues = 0;

    // Check for file path references (machine-verifiable)
    const filePaths = evidence.filter(e => e.includes('/') || e.includes('\\') || e.includes('.md') || e.includes('.json') || e.includes('.sarif') || e.includes('.js'));
    if (filePaths.length === 0) {
      this.issues.push('Evidence has no file path references');
      issues++;
      score -= 15;
    }

    // Check for quantitative data
    const dataRefs = evidence.filter(e => /\d+/.test(e));
    if (dataRefs.length === 0) {
      this.issues.push('Evidence lacks quantitative data (counts, sizes, etc.)');
      issues++;
      score -= 15;
    }

    // Check for source citations or file artifact references (relaxed)
    const citations = evidence.filter(e => {
      const lower = e.toLowerCase();
      return lower.includes('source:') || lower.includes('src:') ||
             lower.includes('url:') || lower.includes('file:') ||
             e.includes('artifacts/') || e.includes('.md') || e.includes('.json') ||
             e.includes('.sarif') || e.includes('.js');
    });
    if (citations.length === 0) {
      this.issues.push('Evidence lacks source citations or artifact refs');
      issues++;
      score -= 10;
    }

    // Check artifact files actually exist on disk (only if they claim to be artifact paths)
    for (const e of evidence) {
      // If the evidence string looks like it contains an artifact path, check it
      const artifactMatch = e.match(/(?:artifacts\/|\/)[a-zA-Z0-9_/-]+\.([a-z]+)/);
      if (artifactMatch) {
        const fullPath = path.resolve(process.cwd(), artifactMatch[0]);
        if (!fs.existsSync(fullPath)) {
          this.issues.push(`Artifact file not found: ${artifactMatch[0]}`);
          issues++;
          score -= 10;
        }
      }
    }

    this.evidence.push(`Evidence quality: ${filePaths.length} file refs, ${dataRefs.length} data refs, ${citations.length} citations/sources`);
    return Math.max(0, score);
  }
}

module.exports = { QualityGate, BANNED_PHRASES, STRUCTURAL_PATTERNS };
